"""
TRIO v2 深度推理模板 — 基于 DeepSeek V4 Pro 结构化 CoT
来源: CRISPE/CO-STAR 框架 + 腾讯云实测（准确率 68%→91%）

核心思路：
  不是 "请分析X"
  而是 6 步结构化推理 + KG 锚定 + 每步标注 + 反例检查
"""

# ============================================================
# 深度推理模板（用于尽调、供应链分析、竞品研究）
# ============================================================
DEEP_REASONING = """## 任务
{task}

## 背景知识（来自 TRIO 知识图谱）
{kg_context}

## 约束条件
{constraints}

## 推理框架 — 请严格按以下结构逐步推理

### Step 1 — 问题边界
这个问题到底在问什么？不在问什么？
标注: [边界定义]

### Step 2 — 已知事实
从背景知识中列出与问题直接相关的事实。每条标注来源。
标注: [事实·KG] 或 [事实·已知]

### Step 3 — 信息缺口
哪些关键信息缺失？你对缺失信息做了什么假设？
标注: [缺口] 或 [假设]

### Step 4 — 核心推理
逐步推导。每一步标注类型：
- [推断·强] — 有直接证据支持
- [推断·弱] — 有部分证据但不确定
- [假设] — 基于推测，无直接证据
- [未知] — 纯猜测

### Step 5 — 反例检查
什么条件/情况会使此结论完全失效？
列出至少 2 个反例场景。
标注: [反例]

### Step 6 — 置信度评估
- 最终结论
- 置信度 (0-100): ___
- 理由: ___
- 最大的不确定性来源: ___
- 如果要多走一步验证，应该验证什么: ___

## 输出规则
- 禁止使用 "显然" "毫无疑问" "众所周知" —— 这些词跳过推理
- 每个推理步骤必须标注类型
- 有分歧的地方标注 [存疑]
- 不确定的事标注 [未知]，不要假装知道
"""

# ============================================================
# 快速推理模板（用于简单判断、速判）
# ============================================================
QUICK_REASONING = """## 判断
{task}

## 已知事实
{kg_context}

请用三段式回答：
1. **判断**: 一句话结论
2. **关键证据**: 支持判断的 2-3 个事实
3. **不确定性**: 如果有什么信息会改变此判断

不要推理步骤，直接给出判断和证据。"""

# ============================================================
# 轨迹合成模板（替代简单投票）
# ============================================================
SYNTHESIZE_PROMPT = """## 任务
综合以下 {num_traces} 个独立推理轨迹，找出收敛点和分歧点。

## 原始问题
{original_question}

## 推理轨迹
{traces}

## 合成规则
1. **收敛点**: 多个轨迹到达同一结论的位置 → 标注 [收敛·高置信]
2. **分歧点**: 不同轨迹得出不同结论 → 标注 [分歧] 并分析原因
3. **证据强度**: 对分歧点，评估各方引用的 KG 证据强度
4. **共错风险**: 收敛点是否因为轨迹们共享了相同假设？标注 [共错风险] 如有
5. **综合结论**: 不是简单投票，是基于证据强度的加权判断

## 输出
```json
{{
  "conclusion": "...",
  "confidence": 0-100,
  "convergence_points": ["...", "..."],
  "divergence_points": [
    {{"issue": "...", "view_a": "...", "view_b": "...", "stronger_side": "a/b/insufficient"}}
  ],
  "shared_assumptions": ["可能共错的假设"],
  "key_evidence": ["决定性证据"]
}}
```
"""

